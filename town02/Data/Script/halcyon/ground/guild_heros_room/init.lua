--Check if a new story event needs to be triggered for a generic day end
function guild_heros_room.CheckTriggerEvent()

	--once bronze rank is obtained in chapter 3, flag chapter 4 to start.
	if SV.ChapterProgression.Chapter == 3 and SV.Chapter3.DefeatedBoss and _DATA.Save.ActiveTeam.Rank ~= "normal" and not SV.TemporaryFlags.Bedtime then
		SV.ChapterProgression.Chapter = 4
		SV.ChapterProgression.UnlockedAssembly = true
		SV.TemporaryFlags.MorningAddress = false--unflag the generic address so the special one can play
		SV.TemporaryFlags.MorningWakeup = false--unflag the generic wakeup so the card can play out properly
		SV.ChapterProgression.CurrentStoryDungeon = "apricorn_grove"
		SV.Dojo.NewMazeUnlocked = true
		SV.metano_cafe.NewDrinkUnlocked = true
		GAME:UnlockDungeon("apricorn_grove")
		--Vague 1 multi-sources : secondaire ch4
		GAME:UnlockDungeon("grotte_echoue")
		--Vague 2 multi-sources : secondaires ch4
		GAME:UnlockDungeon("halles_royales")
		GAME:UnlockDungeon("jardin_secret")
		GAME:UnlockDungeon("flying_maze")--unlock new mazes at ledian dojo
		GAME:UnlockDungeon("rock_maze")--unlock new mazes at ledian dojo
		GAME:WaitFrames(60)
		GeneralFunctions.PromptChapterSaveAndQuit("guild_heros_room", "Main_Entrance_Marker", 2)
	end

	--Start Chapter 5 a few in game days after beating Apricorn Grove.
	if SV.ChapterProgression.Chapter == 4 and SV.Chapter4.FinishedGrove and SV.ChapterProgression.DaysPassed >= SV.ChapterProgression.DaysToReach then
		SV.ChapterProgression.Chapter = 5
		SV.TemporaryFlags.MorningAddress = false--unflag the generic address so the special one can play
		SV.TemporaryFlags.MorningWakeup = false--unflag the generic wakeup so the card can play out properly
		SV.ChapterProgression.CurrentStoryDungeon = ""--clear this; it won't be needed for the expedition
		SV.Dojo.NewMazeUnlocked = true
		--SV.metano_cafe.NewDrinkUnlocked = true
		--GAME:UnlockDungeon("apricorn_grove")
		GAME:UnlockDungeon("electric_maze")--unlock new mazes at ledian dojo
		GAME:UnlockDungeon("bug_maze")--unlock new mazes at ledian dojo
		--Vague 2 multi-sources : secondaires ch5 (route de l'expedition)
		GAME:UnlockDungeon("foret_embuscade")
		GAME:UnlockDungeon("bois_filou")
		GAME:WaitFrames(60)
		GeneralFunctions.PromptChapterSaveAndQuit("guild_heros_room", "Main_Entrance_Marker", 2)
	end

	--Start Chapter 6 a few in game days after finishing the expedition.
	if SV.ChapterProgression.Chapter == 5 and SV.Chapter5.FinishedExpedition and SV.ChapterProgression.DaysPassed >= SV.ChapterProgression.DaysToReach then
		SV.ChapterProgression.Chapter = 6
		SV.TemporaryFlags.MorningAddress = false
		SV.TemporaryFlags.MorningWakeup = false
		SV.ChapterProgression.CurrentStoryDungeon = "gloomy_forest"
		SV.Dojo.NewMazeUnlocked = true
		GAME:UnlockDungeon("gloomy_forest")
		GAME:UnlockDungeon("grass_maze")
		--Vague 2 multi-sources : secondaires ch6
		GAME:UnlockDungeon("desert_oublies")
		GAME:UnlockDungeon("crevasse_geode")
		GAME:WaitFrames(60)
		GeneralFunctions.PromptChapterSaveAndQuit("guild_heros_room", "Main_Entrance_Marker", 2)
	end

	--Start Chapter 7 a few in game days after the Gloomy Forest rescue.
	--
	--CE DECLENCHEUR MANQUAIT : la progression s'arretait au chapitre 6. Tout le
	--contenu du chapitre 7 existait deja et etait cable (carton-titre et reve
	--dans guild_heros_room_ch_7, adresse du matin dans guild_third_floor_lobby_ch_7,
	--dialogues de ville dans metano_town_ch_7, donjon + arene + cinematiques des
	--Aegis Cave), mais rien ne portait jamais Chapter de 6 a 7 : le joueur
	--restait bloque indefiniment en fin de chapitre 6.
	--
	--Le donjon lui-meme n'etait UnlockDungeon nulle part non plus, il faut donc
	--l'ouvrir ici, comme le font les paliers precedents pour leur donjon.
	--
	--Condition alignee sur les paliers ch5 et ch6 : la mission du chapitre est
	--terminee (PostMissionScenePlayed, pose par la scene de retour en ville) et
	--le delai de quelques jours de missions libres est ecoule.
	--VERROU DES REQUETES : le chapitre 7 ne s'ouvre pas tant que les requetes
	--de Metano ne sont pas rendues. Le test est pose ICI en plus de la scene
	--de retour en ville, sinon une nuit passee suffirait a contourner la
	--condition (DaysPassed rattrape DaysToReach tout seul).
	if SV.ChapterProgression.Chapter == 6 and SV.Chapter6.PostMissionScenePlayed
	   and not SideQuests.AllDone(6) then
		SV.ChapterProgression.DaysToReach = SV.ChapterProgression.DaysPassed + 1
	end
	if SV.ChapterProgression.Chapter == 6 and SV.Chapter6.PostMissionScenePlayed and SideQuests.AllDone(6) and SV.ChapterProgression.DaysPassed >= SV.ChapterProgression.DaysToReach then
		SV.ChapterProgression.Chapter = 7
		SV.TemporaryFlags.MorningAddress = false
		SV.TemporaryFlags.MorningWakeup = false
		SV.ChapterProgression.CurrentStoryDungeon = "waterfall_pond"
		SV.Dojo.NewMazeUnlocked = true
		GAME:UnlockDungeon("waterfall_pond")
		--Secondaires ouverts avec le chapitre 7. (water_maze est deja ouvert au
		--chapitre 2 par guild_guildmasters_room_ch_2 : ne pas le redeclarer.)
		GAME:UnlockDungeon("bassin_tari")
		GAME:WaitFrames(60)
		GeneralFunctions.PromptChapterSaveAndQuit("guild_heros_room", "Main_Entrance_Marker", 2)
	end

	--Chapitres 8, 9 et 10 : memes paliers, meme patron.
	--
	--Ces trois chapitres ont leur donjon complet (zone, segments, relais, arene
	--de boss, cinematiques) et leurs dialogues de ville (metano_town_ch_8/9/10),
	--mais aucun d'eux n'etait atteignable : ni declencheur de chapitre, ni
	--UnlockDungeon. Ils sont ouverts ici sur la conclusion du chapitre precedent.
	--
	--Contrairement aux chapitres 1-7, ils n'ont pas de carton-titre ni d'adresse
	--du matin dedies (pas de guild_heros_room_ch_8 ni de
	--guild_third_floor_lobby_ch_8) : le reveil generique s'applique, et la
	--decouverte passe par les dialogues de ville et le donjon lui-meme.
	--------------------------------------------------------------
	-- RESPIRATION ENTRE CHAPITRES (correctif 2026-08-02)
	--
	-- Avant : le palier n'imposait que DaysPassed + 2, et les portes
	-- ch7 a ch10 ne verifiaient AUCUNE quete secondaire — contrairement
	-- a la porte du ch6, seule a exiger SideQuests.AllDone(6). On
	-- enchainait donc donjon -> boss -> veillee -> donjon suivant en
	-- deux nuits, sans jamais rendre une requete.
	--
	-- Desormais, pour passer au chapitre suivant il faut TOUT :
	--   1. le drapeau de cloture du chapitre (le boss est tombe) ;
	--   2. les 3 requetes du chapitre rendues (SideQuests.AllDone) ;
	--   3. le delai de repos ecoule (3 a 5 nuits selon le chapitre).
	--
	-- Le delai n'est pas uniforme : il suit le poids de ce qui vient
	-- de se passer. Apres le Suaire (ch9) et apres le climax (ch10),
	-- la ville a besoin de plus de temps qu'apres un donjon ordinaire.
	--------------------------------------------------------------
	local chapter_gates = {
		--[ch] = { drapeau de cloture, ch suivant, donjon, secondaires, nuits de repos }
		[7]  = { function() return SV.Chapter8.CrystalSanctuaryComplete end, 8,  "poisonous_forest",   {"marais_errants"}, 4 },
		[8]  = { function() return SV.Chapter9.ForgottenMarshComplete end,   9,  "sky_tower",    {"falaises_envol", "sentier_enneige"}, 5 },
		[9]  = { function() return SV.Chapter10.CelestialPeakComplete end,   10, "bourg_comptoir",    {}, 5 },
	}
	local gate = chapter_gates[SV.ChapterProgression.Chapter]
	--Les trois conditions, dans l'ordre du moins couteux au plus couteux
	--a evaluer. AllDone est sous pcall : si le module n'est pas charge,
	--on ne bloque pas le joueur indefiniment.
	local questsDone = true
	if gate ~= nil then
		local ok, res = pcall(function() return SideQuests.AllDone(SV.ChapterProgression.Chapter) end)
		if ok then questsDone = res end
	end
	if gate ~= nil and gate[1]() and questsDone
	   and SV.ChapterProgression.DaysPassed >= SV.ChapterProgression.DaysToReach then
		SV.ChapterProgression.Chapter = gate[2]
		SV.TemporaryFlags.MorningAddress = false
		SV.TemporaryFlags.MorningWakeup = false
		SV.ChapterProgression.CurrentStoryDungeon = gate[3]
		SV.Dojo.NewMazeUnlocked = true
		GAME:UnlockDungeon(gate[3])
		for ii = 1, #gate[4], 1 do
			GAME:UnlockDungeon(gate[4][ii])
		end
		--Repos impose avant le palier suivant : 3 a 5 nuits selon le poids
		--du chapitre qui vient de s'achever (5e champ de la porte).
		SV.ChapterProgression.DaysToReach = SV.ChapterProgression.DaysPassed + (gate[5] or 3)
		GAME:WaitFrames(60)
		GeneralFunctions.PromptChapterSaveAndQuit("guild_heros_room", "Main_Entrance_Marker", 2)
	end

end

function guild_heros_room.PlotScripting()
	--LE CHEVET APRES UN RAID PERDU (RaidScenes.Bedside). Le heros s'est
	--evanoui sur la place : il se reveille ici, et la guilde est deja la.
	--Cette scene passe AVANT tout le reste, y compris le tour de guet :
	--on ne repart pas veiller le soir meme d'un evanouissement, et Phileas
	--le dit explicitement dans la scene.
	--LE CHEVET APRES LA CONFRONTATION DE LA PLACE (DazzlingPlaza).
	--Meme principe que le raid perdu ci-dessous, mais declenche par la
	--defaite contre la Team Dazzling : les habitants ont porte le duo
	--jusqu'ici. Passe avant tout le reste pour la meme raison.
	if SV.Chapter6 ~= nil and SV.Chapter6.PlazaBedsidePending then
		SV.Chapter6.PlazaBedsidePending = false
		SV.TemporaryFlags.Bedtime = false
		SV.TemporaryFlags.MorningWakeup = false
		pcall(function() DazzlingPlaza.Chevet() end)
		return
	end

	local raid = SV.TownRaid or {}
	if raid.BedsidePending then
		raid.BedsidePending = false
		--Le reveil remplace la scene de coucher/matin generique : ces
		--drapeaux sont consommes ici pour ne pas enchainer deux reveils.
		SV.TemporaryFlags.Bedtime = false
		SV.TemporaryFlags.MorningWakeup = false
		pcall(function() RaidScenes.Bedside() end)
		return
	end

	--LE TOUR DE GUET (NightWatch). Il s'insere AVANT le coucher : quand la
	--guilde inscrit l'equipe au registre des veilles, on ne dort pas, on
	--sort veiller sur Metano. C'est ce qui donne une raison NARRATIVE a la
	--ville de nuit, au lieu d'un heros qui se promene sans motif.
	--
	--IsAssigned() rend false des qu'une scene est imposee par le chapitre
	--(memes drapeaux que TownNight.StoryLocked), donc le scenario garde la
	--priorite. Begin() part en ville et pose Bedtime a false : le coucher
	--aura lieu au RETOUR, via TownNight.GoHome().
	if SV.TemporaryFlags.Bedtime and NightWatch.IsAssigned() then
		if NightWatch.Begin() then return end
	end

	--if generic morning is flagged, prioritize that.
	if SV.TemporaryFlags.MorningWakeup or SV.TemporaryFlags.Bedtime then
		if SV.TemporaryFlags.Bedtime then guild_heros_room_helper.Bedtime(true) end

		--Does a new story event need to be triggered?
		guild_heros_room.CheckTriggerEvent()

		if SV.TemporaryFlags.MorningWakeup then guild_heros_room_helper.Morning(true) end

		--RAPPORT DE GARDE (NightWatch). Un devoir accompli doit etre
		--reconnu, sinon ce n'etait pas un devoir. On remplit le registre
		--des veilles au reveil, apres la scene de matin. Deux boites, pas
		--plus : le reste de la journee appartient au chapitre.
		--Ne se joue que si un tour de guet a bien eu lieu la veille.
		if NightWatch.IsOnDuty() then
			pcall(function() NightWatch.Report() end)
			pcall(function() NightWatch.End() end)
		end
	else
		--plot scripting
		if SV.ChapterProgression.Chapter == 1 then
			if SV.Chapter1.TeamCompletedForest and not SV.Chapter1.TeamJoinedGuild then
				guild_heros_room_ch_1.RoomIntro()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 2 then
			if not SV.Chapter2.FinishedFirstWakeup then
				guild_heros_room_ch_2.FirstMorning()
			elseif SV.Chapter2.FinishedNumelTantrum and not SV.Chapter2.FinishedFirstDay then
				guild_heros_room_ch_2.FirstNightBedtalk()
			elseif SV.Chapter2.FinishedRiver then
				guild_heros_room_ch_2.PostRiverBedtalk()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 3 then
			if not SV.Chapter3.ShowedTitleCard then
				guild_heros_room_ch_3.FirstMorning()
			elseif SV.Chapter3.DefeatedBoss and not SV.Chapter3.RootSceneTransition then
				guild_heros_room_ch_3.PostOutlawBedtalkFirstHalf()
			elseif SV.Chapter3.DefeatedBoss and not SV.Chapter3.FinishedRootScene then
				guild_heros_room_ch_3.PostOutlawBedtalkSecondHalf()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 4 then
			if not SV.Chapter4.ShowedTitleCard then
				guild_heros_room_ch_4.ShowTitleCard()
			elseif SV.Chapter4.FinishedGrove and not SV.Chapter4.FinishedBedtimeCutscene then
				guild_heros_room_ch_4.PostGroveBedtalk()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 5 then
			if not SV.Chapter5.ShowedTitleCard then
				guild_heros_room_ch_5.ShowTitleCard()
			elseif SV.Chapter5.FinishedExpedition and not SV.Chapter5.FinishedBedtimeCutscene then
				guild_heros_room_ch_5.PostExpeditionBedtalk()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 6 then
			if not SV.Chapter6.ShowedTitleCard then
				guild_heros_room_ch_6.ShowTitleCard()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 7 then
			if not SV.Chapter7.ShowedTitleCard then
				guild_heros_room_ch_7.ShowTitleCard()
			elseif SV.Chapter7.HeardGenesisTale and not SV.Chapter7.HadFirstDream then
				guild_heros_room_ch_7.DreamCutscene()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 8 then
			--Ces trois chapitres n'avaient NI carton-titre NI scene de chambre :
			--on passait d'un chapitre au suivant sans aucune transition.
			if not SV.Chapter8.ShowedTitleCard then
				guild_heros_room_ch_8.ShowTitleCard()
			elseif SV.Chapter8.CrystalSanctuaryComplete and not SV.Chapter8.FinishedBedtimeCutscene then
				guild_heros_room_ch_8.PostSanctuaryBedtalk()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 9 then
			if not SV.Chapter9.ShowedTitleCard then
				guild_heros_room_ch_9.ShowTitleCard()
			elseif SV.Chapter9.ForgottenMarshComplete and not SV.Chapter9.FinishedBedtimeCutscene then
				guild_heros_room_ch_9.PostMarshBedtalk()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 10 then
			if not SV.Chapter10.ShowedTitleCard then
				guild_heros_room_ch_10.ShowTitleCard()
			elseif SV.Chapter10.CelestialPeakComplete and not SV.Chapter10.FinishedBedtimeCutscene then
				guild_heros_room_ch_10.PostPeakBedtalk()
			else
				GAME:FadeIn(20)
			end
		elseif SV.ChapterProgression.Chapter == 11 then
			if not SV.Chapter11.ShowedTitleCard then
				require 'halcyon.ground.guild_heros_room.guild_heros_room_ch_11'
				guild_heros_room_ch_11.ShowTitleCard()
			else
				GAME:FadeIn(20)
			end
		else
			GAME:FadeIn(20)
		end
	end
end



function guild_heros_room.Book_Action(obj, activator)
	UI:ResetSpeaker(false)
	local hero = GAME:GetPlayerPartyMember(0)
	local partner = GAME:GetPlayerPartyMember(1)
	local hero_ground = CH('PLAYER')
	local partner_ground = CH('Teammate1')
	partner_ground.IsInteracting = true
	GROUND:CharSetAnim(partner_ground, 'None', true)
	GROUND:CharSetAnim(hero_ground, 'None', true)
    GeneralFunctions.TurnTowardsLocation(hero_ground, obj.Position.X + obj.Width // 2, obj.Position.Y + obj.Height // 2)
    GeneralFunctions.TurnTowardsLocation(partner_ground, obj.Position.X + obj.Width // 2, obj.Position.Y + obj.Height // 2)

	--Change where the choice menu goes; put it on the left because of placement of book in the map.
	--UI:SetChoiceLoc(8, 102)

	local choices = {"Changer les foulards", "Changer les surnoms", "Changer le nom de l'équipe", "Voir le rang", "Rien"}
	UI:BeginChoiceMenu("Qu'aimeriez-vous faire ?", choices, 1, #choices)
	UI:WaitForChoice()
	local choice_result = UI:ChoiceResult()

	if choice_result ~= #choices then
		GROUND:ObjectSetDefaultAnim(obj, 'Diary_Red_Opening', 0, 0, 0, Direction.Left)
	    GROUND:ObjectSetAnim(obj, 6, 0, 3, Direction.Left, 1)
		GROUND:ObjectSetDefaultAnim(obj, 'Diary_Red_Opening', 0, 3, 3, Direction.Left)
		GAME:WaitFrames(40)
	end

	if choice_result == 1 then
		local state = 1
		while state > 0 do
			UI:BeginChoiceMenu("De quelle écharpe aimeriez-vous changer ?", {hero_ground:GetDisplayName(), partner_ground:GetDisplayName(), "Neither"}, 1, 3)
			UI:WaitForChoice()
			local chara_choice = UI:ChoiceResult()
			local chara

			if chara_choice == 1 then
				chara = hero_ground
			elseif chara_choice == 2 then
				chara = partner_ground
			else
				state = -1
				break
			end

			--check if sprites exist for that pokemon
			--Current form updates from base form when a new ground/map is entered. Need to change both so the base form is updated proper, and current form needs to change to visually show it without reloading map.
			local monId = RogueEssence.Dungeon.MonsterID(chara.CurrentForm.Species, chara.CurrentForm.Form, 'normal_black', chara.CurrentForm.Gender)
			local fallback = RogueEssence.Content.GraphicsManager.GetFallbackForm(RogueEssence.Content.GraphicsManager.CharaIndex, monId:ToCharID())
			if fallback.Skin == monId:ToCharID().Skin then
				UI:BeginChoiceMenu("Quelle couleur souhaiteriez-vous ?", {"Black", "Blue", "Cyan", "Green", "Magenta", "Orange", "Pink", "Purple", "Red", "White", "Yellow", "No scarf"}, 1, 12)
				UI:WaitForChoice()
				local scarf_choice = UI:ChoiceResult()
				local current_skin = chara.CurrentForm.Skin
				local new_skin
				if scarf_choice == 1 then
					new_skin = "normal_black"
				elseif scarf_choice == 2 then
					new_skin = "normal_blue"
				elseif scarf_choice == 3 then
					new_skin = "normal_cyan"
				elseif scarf_choice == 4 then
					new_skin = "normal_green"
				elseif scarf_choice == 5 then
					new_skin = "normal_magenta"
				elseif scarf_choice == 6 then
					new_skin = "normal_orange"
				elseif scarf_choice == 7 then
					new_skin = "normal_pink"
				elseif scarf_choice == 8 then
					new_skin = "normal_purple"
				elseif scarf_choice == 9 then
					new_skin = "normal_red"
				elseif scarf_choice == 10 then
					new_skin = "normal_white"
				elseif scarf_choice == 11 then
					new_skin = "normal_yellow"
				elseif scarf_choice == 12 then
					new_skin = "normal"
				else
					new_skin = current_skin
				end

				if new_skin ~= current_skin then
					GAME:FadeOut(false, 20)
					chara.Data.BaseForm = RogueEssence.Dungeon.MonsterID(chara.CurrentForm.Species, chara.CurrentForm.Form, new_skin, chara.CurrentForm.Gender)
					chara.Data.CurrentForm = RogueEssence.Dungeon.MonsterID(chara.CurrentForm.Species, chara.CurrentForm.Form, new_skin, chara.CurrentForm.Gender)
					GAME:WaitFrames(20)
					SOUND:PlayBattleSE('_UNK_EVT_023')
					GAME:WaitFrames(40)
					GAME:FadeIn(20)

					GAME:WaitFrames(40)
					if chara_choice == 1 then
						GeneralFunctions.HeroDialogue(chara, "(Ça a l'air bien !)", "Normal")
					else
						UI:SetSpeaker(chara)
						UI:WaitShowDialogue("Ça a l'air bien !")
					end
					GAME:WaitFrames(20)
				end

				state = -1
			else
				UI:WaitShowDialogue("Aucun sprite écharpe n'a encore été créé pour ce Pokémon.[pause=0]Revenez plus tard !")
				state = -1
			end

		end

	elseif choice_result == 2 then
		UI:BeginChoiceMenu("Quel nom souhaiteriez-vous changer ?", {hero_ground:GetDisplayName(), partner_ground:GetDisplayName(), "Neither"}, 1, 3)
		UI:WaitForChoice()
		local name_result = UI:ChoiceResult()

		if name_result == 1 then
			local name = hero.Nickname
			UI:NameMenu("Quel est ton nom?", "Appuie sur [ESC] pour conserver l'ancien surnom.", 60)
			UI:WaitForChoice()
			local result = UI:ChoiceResult()
			--if no name given, set name to previous name
			if result == "" then result = name end
			GAME:SetCharacterNickname(hero, result)
			UI:WaitShowDialogue("Votre nom est désormais " .. hero_ground:GetDisplayName() .. " !")
		elseif name_result == 2 then
			local name = partner.Nickname
			UI:NameMenu("Quel est le nom de votre partenaire ?", "Appuie sur [ESC] pour conserver l'ancien surnom.", 60)
			UI:WaitForChoice()
			local result = UI:ChoiceResult()
			--if no name given, set name to previous name
			if result == "" then result = name end
			GAME:SetCharacterNickname(partner, result)
			UI:WaitShowDialogue("Le nom de votre partenaire est désormais " .. partner_ground:GetDisplayName() .. " !")
		end

	elseif choice_result == 3 then
		local name = _DATA.Save.ActiveTeam.Name
		UI:NameMenu("Quel est le nom de votre équipe ?", "Press [ESC] to keep the old team name.", 60)
		UI:WaitForChoice()
		local result = UI:ChoiceResult()
		--if no name given, set name to previous name
		if result == "" then result = name end
		GAME:SetTeamName(result)
		UI:WaitShowDialogue("Le nom de votre équipe est désormais Team " .. GAME:GetTeamName() .. " !")
	elseif choice_result == 4 then
		local current_rank = _DATA.Save.ActiveTeam.Rank
		local next_rank = _DATA:GetRank(current_rank).Next
		local to_go = _DATA:GetRank(current_rank).FameToNext - _DATA.Save.ActiveTeam.Fame

		UI:WaitShowDialogue("Votre équipe est actuellement[color=#FFA5FF]" .. current_rank:gsub("^%l", string.upper) .. " Rank[color].")
		UI:WaitShowDialogue("Vous avez besoin de points de rang d'aventurier[color=#00FFFF]" .. to_go .. "[color]pour devenir[color=#FFA5FF]" .. next_rank:gsub("^%l", string.upper) .. " Rank[color].")
	end

	if choice_result ~= #choices then
		GROUND:ObjectSetDefaultAnim(obj, 'Diary_Red_Closing', 0, 0, 0, Direction.Left)
		GROUND:ObjectSetAnim(obj, 6, 0, 3, Direction.Left, 1)
		GROUND:ObjectSetDefaultAnim(obj, 'Diary_Red_Closing', 0, 3, 3, Direction.Left)
		GAME:WaitFrames(40)
	end

	--UI:ResetChoiceLoc()
	partner_ground.IsInteracting = false
	GROUND:CharEndAnim(partner_ground)
	GROUND:CharEndAnim(hero_ground)

end



